export const getCustomArticles = () => {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = localStorage.getItem('mc_custom_articles');
      return saved ? JSON.parse(saved) : [];
    }
  } catch (e) {
    // fallback
  }
  return [];
};

export const getDeletedArticleIds = () => {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = localStorage.getItem('mc_deleted_articles');
      return saved ? JSON.parse(saved) : [];
    }
  } catch (e) {
    // fallback
  }
  return [];
};

export const getAllArticles = () => {
  const custom = getCustomArticles();
  const deletedIds = getDeletedArticleIds();
  const customIds = new Set(custom.map((c) => c.id));
  const activeCustom = custom.filter((c) => !deletedIds.includes(c.id));
  const activeBuiltIn = articlesData.filter((a) => !customIds.has(a.id) && !deletedIds.includes(a.id));
  return [...activeCustom, ...activeBuiltIn];
};

export const getArticleBySlug = (slug) => {
  const all = getAllArticles();
  return all.find((art) => art.slug === slug);
};

export const getArticlesByCategory = (categorySlug) => {
  const all = getAllArticles();
  if (!categorySlug || categorySlug === 'todos') return all;
  return all.filter((art) => art.categorySlug === categorySlug);
};

export const searchArticles = (query) => {
  const all = getAllArticles();
  if (!query) return all;
  const q = query.toLowerCase();
  return all.filter(
    (art) =>
      art.title.toLowerCase().includes(q) ||
      (art.h1 && art.h1.toLowerCase().includes(q)) ||
      (art.metaDescription && art.metaDescription.toLowerCase().includes(q)) ||
      (art.keywords && art.keywords.some((k) => k.toLowerCase().includes(q)))
  );
};
